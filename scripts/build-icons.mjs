// Regenerates src/components/polaris-icons.ts from the icon set that Polaris web components (s-icon)
// load from Shopify's CDN — the set the current admin uses. Only icons referenced in src are kept.
// Usage: node scripts/build-icons.mjs
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const out = path.join(root, "src/components/polaris-icons.ts");
const base = "https://cdn.shopify.com/shopifycloud/admin-ui-foundations";

const bundle = await (await fetch("https://cdn.shopify.com/shopifycloud/polaris-2.js")).text();
const list = (name) => {
  const match = bundle.match(new RegExp(`[,;\\s]${name}=(\\[[^\\]]*\\])`));
  if (!match) throw new Error(`icon list ${name} not found in polaris-2.js`);
  return JSON.parse(match[1]);
};
const urls = (entries, dir) => Object.fromEntries(entries.map((entry) => entry.split(" ")).map(([name, hash]) => [name, `${base}/${dir}/${hash}.svg`]));
const filled = { ...urls(list("Zo"), "internal-only"), ...urls(list("eo"), "icons") };
const line = urls(list("Qo"), "experimental");

const kebab = (name) =>
  name
    .replace(/([a-z])([A-Z0-9])/g, "$1-$2")
    .replace(/([A-Z])([A-Z][a-z])/g, "$1-$2")
    .toLowerCase();

function sources(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return sources(full);
    return /\.(tsx?|mjs)$/.test(entry.name) && full !== out ? [fs.readFileSync(full, "utf8")] : [];
  });
}

const wanted = new Set();
for (const text of sources(path.join(root, "src"))) {
  for (const [, name] of text.matchAll(/"([A-Z][A-Za-z0-9]*)"/g)) {
    const id = kebab(name);
    if (line[id] || filled[id]) wanted.add(name);
  }
}

const entries = [];
for (const name of [...wanted].sort()) {
  const id = kebab(name);
  const stroke = Boolean(line[id]);
  const svg = await (await fetch(line[id] ?? filled[id])).text();
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1] ?? "0 0 16 16";
  const [x, y, w, h] = viewBox.split(/\s+/).map(Number);
  const body = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, "")
    // Some CDN files concatenate a second, differently sized <svg>; keep only the first.
    .replace(/<\/svg>[\s\S]*$/, "")
    .replace(/ fill="currentColor"/g, stroke ? ' fill="currentColor" stroke="none"' : ' fill="currentColor"')
    .replace(/\s+/g, " ")
    .trim();
  entries.push(`  ${name}: { viewBox: "${x - w / 8} ${y - h / 8} ${w * 1.25} ${h * 1.25}", stroke: ${stroke}, body: ${JSON.stringify(body)} },`);
}

fs.writeFileSync(
  out,
  `// Generated by scripts/build-icons.mjs from the Polaris web components icon set (s-icon). Do not edit.
export type PolarisGlyph = { viewBox: string; stroke: boolean; body: string };

export const polarisIcons = {
${entries.join("\n")}
} satisfies Record<string, PolarisGlyph>;

export type PolarisIconName = keyof typeof polarisIcons;
`,
);
console.log(`Wrote ${entries.length} icons to ${path.relative(root, out)}`);
